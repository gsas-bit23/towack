#!/usr/bin/env node
// Export only the ABIs the frontend needs from Foundry's out/ into web/src/abi/*.ts.
// Usage (from repo root): forge build && node web/scripts/export-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const outDir = join(repo, "out");
const abiDir = join(repo, "web", "src", "abi");

// [source file, contract name, export name]
const targets = [
  ["TowackToken.sol", "TowackToken", "towackTokenAbi"],
  ["TowackLaunch.sol", "TowackLaunch", "towackLaunchAbi"],
  ["TowackGenesis.sol", "TowackGenesis", "towackGenesisAbi"],
  ["TowackRouter.sol", "TowackRouter", "towackRouterAbi"],
  ["RebateDistributor.sol", "RebateDistributor", "rebateDistributorAbi"],
  ["TeamVesting.sol", "TeamVesting", "teamVestingAbi"],
  ["DrawV2.sol", "DrawV2", "drawV2Abi"],
  ["IAgentId.sol", "IAgentId", "agentIdAbi"],
  ["IPancakeV2.sol", "IPancakeRouter02", "pancakeRouterAbi"],
  ["AgentDeals.sol", "AgentDeals", "agentDealsAbi"],
  ["AgentDealsV2.sol", "AgentDealsV2", "agentDealsV2Abi"],
];

mkdirSync(abiDir, { recursive: true });
const index = [];
for (const [file, name, exportName] of targets) {
  const artifact = JSON.parse(readFileSync(join(outDir, file, `${name}.json`), "utf8"));
  const body =
    `// Generated by web/scripts/export-abi.mjs from out/${file}/${name}.json. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(abiDir, `${name}.ts`), body);
  index.push(`export { ${exportName} } from "./${name}";`);
  console.log(`wrote src/abi/${name}.ts (${artifact.abi.length} entries)`);
}
writeFileSync(join(abiDir, "index.ts"), index.join("\n") + "\n");
